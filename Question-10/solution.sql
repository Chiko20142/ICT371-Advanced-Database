-- ============================================================
-- PART (b): FUNCTION - fn_scholarship_eligible
-- Checks all three scholarship eligibility conditions.
-- ============================================================

CREATE OR REPLACE FUNCTION fn_scholarship_eligible(
    p_age INTEGER,
    p_income NUMERIC,
    p_mark NUMERIC
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
BEGIN

    -- Reject NULL inputs
    IF p_age IS NULL
       OR p_income IS NULL
       OR p_mark IS NULL THEN

        RAISE EXCEPTION
            'Age, income and average mark cannot be NULL';

    END IF;

    -- Validate age
    IF p_age <= 0 THEN
        RAISE EXCEPTION
            'Age must be greater than zero';
    END IF;

    -- Validate income
    IF p_income < 0 THEN
        RAISE EXCEPTION
            'Monthly income cannot be negative';
    END IF;

    -- Validate average mark
    IF p_mark < 0 OR p_mark > 100 THEN
        RAISE EXCEPTION
            'Average mark must be between 0 and 100';
    END IF;

    -- Check all scholarship eligibility conditions
    RETURN (
        p_age BETWEEN 18 AND 25
        AND p_income <= 3000
        AND p_mark >= 70
    );

END;
$$;


