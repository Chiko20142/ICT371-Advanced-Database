-- ============================================================
-- PART (g): PROCEDURE - pr_assess_pending
-- Uses a query FOR loop to process only PENDING applications.
-- Already assessed applications are not processed again.
-- ============================================================

CREATE OR REPLACE PROCEDURE pr_assess_pending()
LANGUAGE plpgsql
AS $$
DECLARE
    v_application RECORD;
BEGIN

    -- Loop through only PENDING applications
    FOR v_application IN
        SELECT application_id
        FROM applications
        WHERE status = 'PENDING'
        ORDER BY application_id
    LOOP

        -- Assess each pending application
        CALL pr_assess_application(
            v_application.application_id
        );

    END LOOP;

    RAISE NOTICE
        'All pending applications have been assessed';

END;
$$;


