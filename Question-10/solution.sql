-- ============================================================
-- PART (d): TRIGGER
-- AFTER UPDATE trigger that records actual status changes.
-- Uses OLD and NEW values.
-- ============================================================

CREATE OR REPLACE FUNCTION fn_audit_application_status()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    -- Only record an audit when status actually changes
    IF OLD.status IS DISTINCT FROM NEW.status THEN

        INSERT INTO decision_audit (
            application_id,
            old_status,
            new_status,
            changed_at
        )
        VALUES (
            NEW.application_id,
            OLD.status,
            NEW.status,
            CURRENT_TIMESTAMP
        );

    END IF;

    RETURN NEW;

END;
$$;


-- Create the AFTER UPDATE trigger
CREATE OR REPLACE TRIGGER trg_audit_application_status
AFTER UPDATE ON applications
FOR EACH ROW
EXECUTE FUNCTION fn_audit_application_status();


-- ============================================================
-- PART (c): PROCEDURE - pr_assess_application
-- Processes one application.
-- Updates status to APPROVED or REJECTED.
-- ============================================================

CREATE OR REPLACE PROCEDURE pr_assess_application(
    p_application_id INTEGER
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_age INTEGER;
    v_income NUMERIC(12,2);
    v_mark NUMERIC(5,2);
    v_status VARCHAR(20);
    v_eligible BOOLEAN;
BEGIN

    -- Find the application
    SELECT
        age_at_application,
        monthly_income,
        average_mark,
        status
    INTO
        v_age,
        v_income,
        v_mark,
        v_status
    FROM applications
    WHERE application_id = p_application_id
    FOR UPDATE;

    -- Reject an unknown application
    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Application ID % does not exist',
            p_application_id;
    END IF;

    -- Only PENDING applications can be assessed
    IF v_status <> 'PENDING' THEN
        RAISE EXCEPTION
            'Application ID % has already been assessed. Current status: %',
            p_application_id,
            v_status;
    END IF;

    -- Call the eligibility function
    v_eligible := fn_scholarship_eligible(
        v_age,
        v_income,
        v_mark
    );

    -- Update application status
    IF v_eligible THEN

        UPDATE applications
        SET status = 'APPROVED'
        WHERE application_id = p_application_id;

        RAISE NOTICE
            'Application % has been APPROVED',
            p_application_id;

    ELSE

        UPDATE applications
        SET status = 'REJECTED'
        WHERE application_id = p_application_id;

        RAISE NOTICE
            'Application % has been REJECTED',
            p_application_id;

    END IF;

END;
$$;


