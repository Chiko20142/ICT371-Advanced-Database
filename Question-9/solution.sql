-- ============================================================
-- PART (g): DAILY PURCHASES REFRESH PROCEDURE
-- Calculates the total weight and value for a given date.
-- ON CONFLICT replaces the existing date's totals.
-- ============================================================

CREATE OR REPLACE PROCEDURE pr_refresh_purchases(
    p_day DATE
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_total_weight NUMERIC(14,2);
    v_total_value NUMERIC(14,2);
BEGIN

    IF p_day IS NULL THEN
        RAISE EXCEPTION
            'Purchase date cannot be NULL';
    END IF;

    -- Calculate total purchased weight and value
    SELECT
        COALESCE(SUM(weight_kg), 0),
        COALESCE(SUM(total_value), 0)
    INTO
        v_total_weight,
        v_total_value
    FROM deliveries
    WHERE delivered_on = p_day;

    -- Insert or replace the daily purchase totals
    INSERT INTO daily_purchases (
        purchase_date,
        total_weight,
        total_value
    )
    VALUES (
        p_day,
        v_total_weight,
        v_total_value
    )
    ON CONFLICT (purchase_date)
    DO UPDATE SET
        total_weight = EXCLUDED.total_weight,
        total_value = EXCLUDED.total_value;

    RAISE NOTICE
        'Daily purchases refreshed for %',
        p_day;

END;
$$;


