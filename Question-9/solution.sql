-- Create farmers table
CREATE TABLE IF NOT EXISTS farmers (
    farmer_id INTEGER PRIMARY KEY,
    farmer_number VARCHAR(30) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL
);


-- Create deliveries table
CREATE TABLE IF NOT EXISTS deliveries (
    delivery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id INTEGER NOT NULL,
    grade VARCHAR(1) NOT NULL,
    weight_kg NUMERIC(12,2) NOT NULL,
    unit_rate NUMERIC(10,2) NOT NULL DEFAULT 0,
    total_value NUMERIC(14,2) NOT NULL DEFAULT 0,
    delivered_on DATE NOT NULL,
    is_paid BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_delivery_farmer
        FOREIGN KEY (farmer_id)
        REFERENCES farmers(farmer_id),

    CONSTRAINT chk_delivery_grade
        CHECK (grade IN ('A', 'B', 'C')),

    CONSTRAINT chk_delivery_weight
        CHECK (weight_kg > 0),

    CONSTRAINT chk_delivery_unit_rate
        CHECK (unit_rate >= 0),

    CONSTRAINT chk_delivery_total_value
        CHECK (total_value >= 0)
);


-- Create daily purchases table
CREATE TABLE IF NOT EXISTS daily_purchases (
    purchase_date DATE PRIMARY KEY,
    total_weight NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_value NUMERIC(14,2) NOT NULL DEFAULT 0,

    CONSTRAINT chk_total_weight
        CHECK (total_weight >= 0),

    CONSTRAINT chk_total_value
        CHECK (total_value >= 0)
);


