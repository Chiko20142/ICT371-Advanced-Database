-- ============================================================
-- PART (b): FUNCTION - fn_maize_rate
-- Grade A = K5 per kg
-- Grade B = K4 per kg
-- Grade C = K3 per kg
-- Reject NULL or unsupported grades.
-- ============================================================

CREATE OR REPLACE FUNCTION fn_maize_rate(
    p_grade VARCHAR
)
RETURNS NUMERIC(10,2)
LANGUAGE plpgsql
AS $$
DECLARE
    v_rate NUMERIC(10,2);
BEGIN

    IF p_grade IS NULL THEN
        RAISE EXCEPTION 'Grade cannot be NULL';
    END IF;

    CASE UPPER(TRIM(p_grade))
        WHEN 'A' THEN
            v_rate := 5.00;

        WHEN 'B' THEN
            v_rate := 4.00;

        WHEN 'C' THEN
            v_rate := 3.00;

        ELSE
            RAISE EXCEPTION
                'Invalid maize grade: %', p_grade;
    END CASE;

    RETURN v_rate;

END;
$$;


