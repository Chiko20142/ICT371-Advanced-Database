-- ============================================================
-- PART (d): TRIGGER
-- BEFORE INSERT OR UPDATE trigger.
-- Rejects non-positive weight and automatically calculates
-- unit_rate and total_value.
-- ============================================================

CREATE OR REPLACE FUNCTION fn_calculate_delivery_value()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN

    -- Reject invalid weight
    IF NEW.weight_kg IS NULL OR NEW.weight_kg <= 0 THEN
        RAISE EXCEPTION
            'Delivery weight must be greater than zero';
    END IF;

    -- Validate grade and obtain its price
    NEW.unit_rate := fn_maize_rate(NEW.grade);

    -- Calculate total delivery value
    NEW.total_value := ROUND(
        NEW.weight_kg * NEW.unit_rate,
        2
    );

    RETURN NEW;

END;
$$;


-- Create the trigger
CREATE OR REPLACE TRIGGER trg_calculate_delivery_value
BEFORE INSERT OR UPDATE ON deliveries
FOR EACH ROW
EXECUTE FUNCTION fn_calculate_delivery_value();


-- ============================================================
-- PART (c): PROCEDURE - pr_receive_delivery
-- Validates farmer and delivery information.
-- Inserts the basic fields with is_paid set to FALSE.
-- The trigger calculates unit_rate and total_value.
-- ============================================================

CREATE OR REPLACE PROCEDURE pr_receive_delivery(
    p_farmer_id INTEGER,
    p_grade VARCHAR,
    p_weight NUMERIC,
    p_date DATE
)
LANGUAGE plpgsql
AS $$
BEGIN

    -- Check whether the farmer exists
    IF NOT EXISTS (
        SELECT 1
        FROM farmers
        WHERE farmer_id = p_farmer_id
    ) THEN
        RAISE EXCEPTION
            'Farmer ID % does not exist', p_farmer_id;
    END IF;

    -- Validate grade
    IF p_grade IS NULL THEN
        RAISE EXCEPTION 'Grade cannot be NULL';
    END IF;

    -- Validate weight
    IF p_weight IS NULL OR p_weight <= 0 THEN
        RAISE EXCEPTION
            'Weight must be greater than zero';
    END IF;

    -- Validate delivery date
    IF p_date IS NULL THEN
        RAISE EXCEPTION
            'Delivery date cannot be NULL';
    END IF;

    -- Validate the grade using the function
    PERFORM fn_maize_rate(p_grade);

    -- Insert basic delivery details.
    -- The BEFORE trigger supplies unit_rate and total_value.
    INSERT INTO deliveries (
        farmer_id,
        grade,
        weight_kg,
        delivered_on,
        is_paid
    )
    VALUES (
        p_farmer_id,
        UPPER(TRIM(p_grade)),
        p_weight,
        p_date,
        FALSE
    );

    RAISE NOTICE
        'Delivery recorded successfully for farmer %',
        p_farmer_id;

END;
$$;


