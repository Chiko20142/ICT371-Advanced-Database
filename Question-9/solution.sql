-- ============================================================
-- SCHEDULED JOB
-- Run daily at 01:30.
-- The job processes the previous day's deliveries.
-- Requires pg_cron to be installed and configured.
-- ============================================================

CREATE EXTENSION IF NOT EXISTS pg_cron;


-- Schedule the daily refresh
SELECT cron.schedule(
    'refresh-daily-purchases',
    '30 1 * * *',
    $job$
        CALL pr_refresh_purchases(
            (CURRENT_DATE - INTERVAL '1 day')::DATE
        );
    $job$
);


-- Inspect the scheduled job
SELECT *
FROM cron.job
WHERE jobname = 'refresh-daily-purchases';


-- Inspect scheduled job execution history
SELECT *
FROM cron.job_run_details
ORDER BY start_time DESC
LIMIT 10;


