-- ============================================================
-- PART (e): VIEW - v_farmer_amount_due
-- Shows every farmer, including farmers with no unpaid
-- deliveries. Their unpaid amount is displayed as zero.
-- ============================================================

CREATE OR REPLACE VIEW v_farmer_amount_due AS
SELECT
    f.farmer_number,
    f.full_name,
    COALESCE(
        SUM(
            CASE
                WHEN d.is_paid = FALSE
                THEN d.total_value
                ELSE 0
            END
        ),
        0
    ) AS total_unpaid_value
FROM farmers f
LEFT JOIN deliveries d
    ON f.farmer_id = d.farmer_id
GROUP BY
    f.farmer_id,
    f.farmer_number,
    f.full_name;


-- Query the view
SELECT *
FROM v_farmer_amount_due
ORDER BY farmer_number;


