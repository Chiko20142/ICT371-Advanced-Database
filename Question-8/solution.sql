-- ============================================================
-- PART (g): SERVICE ALERT REFRESH PROCEDURE
-- Inserts or updates alerts for vehicles that are due.
-- Removes alerts when vehicles are no longer due.
-- ============================================================

CREATE OR REPLACE PROCEDURE pr_refresh_service_alerts()
LANGUAGE plpgsql
AS $$
BEGIN

    -- Insert or update alerts for vehicles due for service
    INSERT INTO service_alerts (
        vehicle_id,
        km_since_service,
        flagged_on
    )
    SELECT
        vehicle_id,
        (current_odometer - last_service_odometer),
        CURRENT_DATE
    FROM vehicles
    WHERE
        (current_odometer - last_service_odometer) >= 5000

    ON CONFLICT (vehicle_id)
    DO UPDATE SET
        km_since_service = EXCLUDED.km_since_service,
        flagged_on = EXCLUDED.flagged_on;


    -- Remove alerts for vehicles that are no longer due
    DELETE FROM service_alerts
    WHERE vehicle_id IN (
        SELECT v.vehicle_id
        FROM vehicles v
        WHERE
            (v.current_odometer - v.last_service_odometer) < 5000
    );

    RAISE NOTICE 'Service alerts refreshed successfully';

END;
$$;


