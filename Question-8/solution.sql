-- ============================================================
-- PART (c): PROCEDURE - pr_record_trip
-- Validates the vehicle and mileage, then inserts the trip.
-- The trigger updates the vehicle odometer.
-- ============================================================

CREATE OR REPLACE PROCEDURE pr_record_trip(
    p_vehicle_id INTEGER,
    p_trip_on DATE,
    p_start NUMERIC,
    p_end NUMERIC
)
LANGUAGE plpgsql
AS $$
BEGIN

    -- Check that the vehicle exists
    IF NOT EXISTS (
        SELECT 1
        FROM vehicles
        WHERE vehicle_id = p_vehicle_id
    ) THEN
        RAISE EXCEPTION
            'Vehicle ID % does not exist', p_vehicle_id;
    END IF;

    -- Validate trip date
    IF p_trip_on IS NULL THEN
        RAISE EXCEPTION 'Trip date cannot be NULL';
    END IF;

    -- Validate odometer values
    IF p_start IS NULL OR p_end IS NULL THEN
        RAISE EXCEPTION 'Odometer values cannot be NULL';
    END IF;

    IF p_start < 0 OR p_end < 0 THEN
        RAISE EXCEPTION
            'Odometer values cannot be negative';
    END IF;

    IF p_end <= p_start THEN
        RAISE EXCEPTION
            'End odometer must be greater than start odometer';
    END IF;

    -- Insert trip.
    -- The BEFORE INSERT trigger updates the vehicle odometer.
    INSERT INTO trips (
        vehicle_id,
        trip_on,
        start_odometer,
        end_odometer
    )
    VALUES (
        p_vehicle_id,
        p_trip_on,
        p_start,
        p_end
    );

    RAISE NOTICE 'Trip recorded successfully for vehicle %',
        p_vehicle_id;

END;
$$;


