-- ============================================================
-- PART (d): TRIGGER
-- BEFORE INSERT trigger on trips.
-- Checks the starting odometer and updates the vehicle's
-- current odometer exactly once.
-- ============================================================

CREATE OR REPLACE FUNCTION fn_validate_trip()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_current_odometer NUMERIC(12,2);
BEGIN

    -- Lock the vehicle row and get its current odometer
    SELECT current_odometer
    INTO v_current_odometer
    FROM vehicles
    WHERE vehicle_id = NEW.vehicle_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Vehicle ID % does not exist', NEW.vehicle_id;
    END IF;

    -- Validate starting odometer
    IF NEW.start_odometer <> v_current_odometer THEN
        RAISE EXCEPTION
            'Trip must start at the vehicle current odometer. Current value: %',
            v_current_odometer;
    END IF;

    -- Validate trip distance
    IF NEW.end_odometer <= NEW.start_odometer THEN
        RAISE EXCEPTION
            'End odometer must be greater than start odometer';
    END IF;

    -- Update vehicle odometer exactly once
    UPDATE vehicles
    SET current_odometer = NEW.end_odometer
    WHERE vehicle_id = NEW.vehicle_id;

    RETURN NEW;
END;
$$;


-- Create the BEFORE INSERT trigger
CREATE OR REPLACE TRIGGER trg_validate_trip
BEFORE INSERT ON trips
FOR EACH ROW
EXECUTE FUNCTION fn_validate_trip();


-- ============================================================
-- PART (b): FUNCTION - fn_service_due
-- Returns TRUE when a vehicle has travelled at least
-- 5,000 kilometres since its last service.
-- ============================================================

CREATE OR REPLACE FUNCTION fn_service_due(
    p_vehicle_id INTEGER
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    v_current_odometer NUMERIC(12,2);
    v_last_service NUMERIC(12,2);
BEGIN

    SELECT current_odometer, last_service_odometer
    INTO v_current_odometer, v_last_service
    FROM vehicles
    WHERE vehicle_id = p_vehicle_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Vehicle ID % does not exist', p_vehicle_id;
    END IF;

    IF (v_current_odometer - v_last_service) >= 5000 THEN
        RETURN TRUE;
    ELSE
        RETURN FALSE;
    END IF;

END;
$$;


