-- PART (e): VIEW - v_service_due
-- Shows vehicles that have travelled at least 5,000 km
-- since their last service.
-- ============================================================

CREATE OR REPLACE VIEW v_service_due AS
SELECT
    registration,
    (current_odometer - last_service_odometer)
        AS km_since_service
FROM vehicles
WHERE
    (current_odometer - last_service_odometer) >= 5000;


